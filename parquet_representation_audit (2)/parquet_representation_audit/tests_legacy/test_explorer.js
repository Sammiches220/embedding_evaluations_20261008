/* Numerical tests only; UI rendering is not inferred from these checks. */
const assert=require('node:assert/strict');
const core=require('../embedding_feature_audit/assets/explorer.js');
const graph=[[1,3],[0,2],[0,3],[0,1]], rows=[0,1,2,3];
const numeric={kind:'continuous',values:[0,10,20,null]};
const category={kind:'categorical',values:['a','a','b',null]};
const tags={kind:'multilabel',values:[['water','night'],['water'],['sky'],null]};
const src=core.source(category,rows,['a','b']);
assert.equal(src.coverage,.75);
assert.ok(Math.abs(src.diversity-.9182958340544896)<1e-12);
assert.equal(core.source(category,[0,1],['a','b']).diversity,0);
assert.equal(core.source(category,[],['a','b']).diversity,null);
const numericSource=core.source(numeric,rows,[]);
assert.equal(numericSource.mean,10);
assert.ok(Math.abs(numericSource.variance-200/3)<1e-12);
const geom=core.geometry(numeric,[],graph,rows,2,numericSource,[]);
assert.equal(geom.mean_neighbor_abs_difference,12.5);
assert.equal(geom.mean_local_variance,100/3);
assert.equal(geom.variance_ratio_to_global,.5);
assert.equal(geom.morans_i,-.375);
const catGeom=core.geometry(category,['a','b'],graph,rows,2,src,[2/3,1/3]);
assert.equal(catGeom.entropy,1/3);
assert.equal(catGeom.micro_purity,.5);
assert.equal(catGeom.macro_purity,.375);
assert.equal(catGeom.micro_lift,.75);
const tagGeom=core.geometry(tags,['water','night'],graph,rows,2,{},[2/3,1/3]);
assert.equal(tagGeom.micro_purity,.5);
assert.equal(tagGeom.macro_purity,.375);
assert.equal(core.classify(.3,.02,'up',true),'good');
assert.equal(core.classify(-.3,.02,'down',true),'good');
assert.equal(core.classify(.3,.02,'descriptive',true),'up');
assert.equal(core.classify(0,.02,'up',false),'warn');
const records=[{row_position:0,model:'linear',true:'a',predicted:'a'},{row_position:1,model:'linear',true:'b',predicted:'a'},{row_position:0,model:'baseline',true:'a',predicted:'a'}];
assert.equal(core.probe(records,[0,1],'categorical','linear').balanced_accuracy,.5);
assert.equal(core.probe(records,[0],'categorical','linear').n_classes,1);
assert.equal(core.probe(records,[],'categorical','linear').n_compared,0);
assert.equal(core.metrics([0,2],[0,0],'continuous').r2,-1);
assert.equal(core.metrics([1],[1],'continuous').r2,null);
assert.equal(core.metrics([1,1],[0,0],'continuous').r2,0);
assert.equal(core.external({...category,predictions:['a','b','b',null]},rows,['a','b']).balanced_accuracy,.75);
assert.ok(core.curveMeaning([.2,.4,.1],[5,10,25],[5,10]).includes('increases'));
assert.ok(core.curveMeaning([.2,.4,.1],[5,10,25],[]).includes('Too few'));
console.log('Feature overview numerical checks passed.');
